class LiveActivityModel {
  final String title;
  final String amount;
  final String time;
  final String date;
  final int views;
  final int likes;
  final int comments;

  LiveActivityModel({
    required this.title,
    required this.amount,
    required this.time,
    required this.date,
    required this.views,
    required this.likes,
    required this.comments,
  });
}
